#!/bin/zsh
# Regenerates Vendor/highlighting from VS Code's built-in extensions (MIT) at a pinned tag, plus
# vscode-textmate and vscode-oniguruma (MIT) from npm. Needs git, node and npm; the app build doesn't.
#   scripts/update-highlighting.sh [vscode tag]
set -euo pipefail
ROOT=${0:A:h}/..
TAG=${1:-1.147.0}
TOOLS=$ROOT/tools/highlighting
OUT=$ROOT/Vendor/highlighting
WORK=$(mktemp -d)
trap 'rm -rf $WORK' EXIT

git clone -q --depth 1 --filter=blob:none --no-checkout --branch $TAG https://github.com/microsoft/vscode.git $WORK/vscode
git -C $WORK/vscode sparse-checkout set --no-cone '/extensions/*/syntaxes/' '/extensions/*/package.json' '/extensions/theme-defaults/' '/LICENSE.txt'
git -C $WORK/vscode checkout -q

(cd $TOOLS && npm ci --silent && npm run -s build)
node $TOOLS/prepare-assets.mjs $WORK/vscode $OUT 2026-light.json 2026-dark.json
cp $TOOLS/build/highlighter.js $TOOLS/node_modules/vscode-oniguruma/release/onig.wasm $OUT/

mkdir -p $OUT/licenses
cp $WORK/vscode/LICENSE.txt $OUT/licenses/vscode-LICENSE.txt
cp $TOOLS/node_modules/vscode-textmate/LICENSE.md $OUT/licenses/vscode-textmate-LICENSE.md
cp $TOOLS/node_modules/vscode-oniguruma/LICENSE.txt $OUT/licenses/vscode-oniguruma-LICENSE.txt
cp $TOOLS/node_modules/vscode-oniguruma/NOTICES.txt $OUT/licenses/vscode-oniguruma-NOTICES.txt
cat > $OUT/SOURCE.md <<M
# Bundled highlighting assets

Generated by \`scripts/update-highlighting.sh\`; don't edit by hand.

- Grammars, language definitions and the "2026 Light"/"2026 Dark" themes: VS Code $TAG built-in extensions, MIT (licenses/vscode-LICENSE.txt). Individual grammars carry their upstream origin in their own metadata.
- highlighter.js: vscode-textmate $(node -p "require('$TOOLS/node_modules/vscode-textmate/package.json').version") (MIT) and vscode-oniguruma $(node -p "require('$TOOLS/node_modules/vscode-oniguruma/package.json').version") (MIT), bundled with tools/highlighting/entry.js.
- onig.wasm: vscode-oniguruma (Oniguruma, BSD; see licenses/vscode-oniguruma-NOTICES.txt).
M
echo "updated $OUT from VS Code $TAG"
